#!/usr/bin/env python3
"""WAD level importer for deadman-3d: real DOOM-format geometry -> the 64x64 grid.

Two sources, one pipeline (see ``deadman3d.py`` for the consumer):

* **Freedoom mode** (``--freedoom DIR``): a checkout/snapshot of
  https://github.com/freedoom/freedoom (pinned commit ``d14dbbe``).  The level
  is ``levels/<map>.wad`` (a PWAD of just the map lumps), wall textures are
  composited from ``lumps/textures/textures.cfg`` + ``patches/*.png``, and the
  title screen is ``graphics/titlepic/titlepic.png``.  Freedoom content is
  BSD-licensed (COPYING.adoc) — the committed deadman-3d map, wall families
  and title screen are generated by this mode.

* **IWAD mode** (``--wad PATH``): a retail-format IWAD (e.g. a DOOM shareware
  ``DOOM1.WAD``).  Everything comes from inside the WAD: map lumps,
  ``TEXTURE1``/``TEXTURE2`` + ``PNAMES`` + patch lumps (DOOM picture format)
  + ``PLAYPAL`` for wall colours, ``TITLEPIC`` for the title.  **Nothing
  derived from a retail IWAD may be committed** — outputs belong in a
  git-ignored directory (``littleman/examples/local/``).

The pipeline:

1. Parse the WAD directory (12-byte header, 16-byte directory entries) and the
   fixed-size little-endian map lumps: VERTEXES (4 bytes: x, y), LINEDEFS
   (14 bytes), SIDEDEFS (30 bytes), THINGS (10 bytes).
2. Rasterize: the level bbox is fitted (uniform scale, centred, one-cell
   border) onto a ``grid``x``grid`` map.  Every **one-sided** linedef at least
   ``min_len`` map units long becomes wall cells via an exact supercover
   traversal; two-sided linedefs (room-to-room joins, doorways) and shorter
   detail lines are ignored.  Each wall cell inherits its dominant linedef's
   sidedef texture (weighted by linedef length).
3. Close the map: the player start (THINGS type 1, bumped to the nearest open
   cell if its own cell caught a wall) seeds a 4-connected flood fill; the
   reachable region must not touch the grid border (watertightness — a
   supercover of the level's closed one-sided perimeter cannot be crossed),
   and every unreachable cell is filled solid, so the committed map has no
   void a ray could escape into.
4. Colour: each texture name that occurs on a wall cell maps to a wall family
   1..7 — the ANSI palette index of its average colour (patches composited,
   alpha-weighted).  Because most DOOM-era textures are desaturated, the
   family is chosen by *hue* (CIELAB, families 1..6) with a chroma gate below
   which the texture is gray (family 7); ties collapse identical-hue textures
   into one family, which is the <=7-group clustering.
5. Title: the 320x200 title art (PNG or TITLEPIC picture lump) is quantized to
   64x48 with the repo's block-Lab method — per target block, the ANSI-16
   colour minimizing the sum of CIELAB distances over the source block's
   pixels — after a fixed x1.6 brightness lift (DOOM-era title art is dark;
   measured on both sources), then a single isolated-dot despeckle pass.

The output bundle (``--out DIR``) is ``level.json`` (map rows, spawn, heading,
title rows, the texture->family table) plus eyeball artifacts: ``map.txt``,
``title.txt``, ``overhead.png``, ``title.png``, ``families.txt``.

Stdlib only (struct + zlib carry the PNG codec) so the fast tests can cover
the parser on a synthetic in-memory WAD.
"""
